package com.bravetube.tv.data

import kotlinx.serialization.Serializable

/**
 * Wire models for the Piped API (https://docs.piped.video/docs/api-documentation/).
 * Every field is nullable / defaulted because public instances vary in what they return.
 */

@Serializable
data class StreamItem(
    val url: String? = null,
    val type: String? = null,
    val title: String? = null,
    val thumbnail: String? = null,
    val uploaderName: String? = null,
    val uploaderUrl: String? = null,
    val uploaderAvatar: String? = null,
    val uploadedDate: String? = null,
    val shortDescription: String? = null,
    val duration: Long = -1,
    val views: Long = -1,
    val uploaded: Long = -1,
    val uploaderVerified: Boolean = false,
    val isShort: Boolean = false,

    // channel-result fields
    val name: String? = null,
    val description: String? = null,
    val subscribers: Long = -1,
    val videos: Long = -1,
    val avatar: String? = null,
    val verified: Boolean = false,
) {
    val videoId: String?
        get() = url?.let { extractVideoId(it) }

    val channelId: String?
        get() = extractChannelId(url) ?: extractChannelId(uploaderUrl)

    val displayTitle: String get() = title ?: name.orEmpty()
    val displayThumb: String? get() = thumbnail ?: avatar
    val isChannel: Boolean get() = type == "channel"
    val isPlaylist: Boolean get() = type == "playlist"
    val isVideo: Boolean get() = !isChannel && !isPlaylist
}

@Serializable
data class SearchResponse(
    val items: List<StreamItem> = emptyList(),
    val nextpage: String? = null,
    val suggestion: String? = null,
    val corrected: Boolean = false,
)

@Serializable
data class PipedStream(
    val url: String? = null,
    val format: String? = null,
    val quality: String? = null,
    val mimeType: String? = null,
    val codec: String? = null,
    val videoOnly: Boolean = false,
    val bitrate: Long = 0,
    val width: Int = 0,
    val height: Int = 0,
    val fps: Int = 0,
    val contentLength: Long = -1,
    val audioTrackName: String? = null,
) {
    /** "1080p60" -> 1080, "144p" -> 144, "" -> 0 */
    val heightPx: Int
        get() = if (height > 0) height else quality?.substringBefore("p")?.toIntOrNull() ?: 0

    val label: String
        get() = quality ?: (if (heightPx > 0) "${heightPx}p" else "auto")
}

