// ---------------------------------------------------------------- helpers

fun extractVideoId(url: String): String? {
    if (url.isBlank()) return null
    val marker = "v="
    val i = url.indexOf(marker)
    if (i >= 0) {
        val raw = url.substring(i + marker.length).substringBefore('&')
        if (raw.isNotBlank()) return raw
    }
    if (url.contains("youtu.be/")) {
        val raw = url.substringAfter("youtu.be/").substringBefore('?').substringBefore('&')
        if (raw.isNotBlank()) return raw
    }
    // bare id
    if (url.length == 11 && !url.contains('/')) return url
    return null
}

fun extractChannelId(url: String?): String? {
    if (url.isNullOrBlank()) return null
    val marker = "/channel/"
    val i = url.indexOf(marker)
    if (i < 0) return null
    val raw = url.substring(i + marker.length).substringBefore('?').substringBefore('/')
    return raw.takeIf { it.isNotBlank() }
}

fun formatViews(views: Long): String = when {
    views < 0 -> ""
    views >= 1_000_000_000 -> String.format("%.1fB views", views / 1_000_000_000.0)
    views >= 1_000_000 -> String.format("%.1fM views", views / 1_000_000.0)
    views >= 1_000 -> String.format("%.1fK views", views / 1_000.0)
    else -> "$views views"
}

fun formatSubs(subs: Long): String = when {
    subs < 0 -> ""
    subs >= 1_000_000 -> String.format("%.1fM subscribers", subs / 1_000_000.0)
    subs >= 1_000 -> String.format("%.1fK subscribers", subs / 1_000.0)
    else -> "$subs subscribers"
}

/** seconds -> 1:02:03 / 4:05 */
fun formatDuration(seconds: Long): String {
    if (seconds <= 0) return ""
    val h = seconds / 3600
    val m = (seconds % 3600) / 60
    val s = seconds % 60
    return if (h > 0) String.format("%d:%02d:%02d", h, m, s) else String.format("%d:%02d", m, s)
}

/** milliseconds -> 1:02:03 / 4:05, always renders (used by the player scrubber) */
fun formatPosition(ms: Long): String {
    val safe = if (ms < 0) 0 else ms / 1000
    val h = safe / 3600
    val m = (safe % 3600) / 60
    val s = safe % 60
    return if (h > 0) String.format("%d:%02d:%02d", h, m, s) else String.format("%d:%02d", m, s)
}
